"""Location safety models used by patient devices and caregiver APIs.

These models intentionally avoid any map-SDK dependency. Android clients can
upload locations from AMap, Baidu, Google Maps, or manual sources through the
same backend contract.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any


@dataclass(slots=True)
class PatientLocation:
    """Latest known location reported for one patient."""

    patient_id: str
    latitude: float
    longitude: float
    accuracy: float | None = None
    address_text: str | None = None
    source: str | None = None
    timestamp: str = ""

    @classmethod
    def from_row(cls, row: Any) -> "PatientLocation":
        """Build a location object from a SQLite row."""
        return cls(
            patient_id=row["patient_id"],
            latitude=float(row["latitude"]),
            longitude=float(row["longitude"]),
            accuracy=float(row["accuracy"]) if row["accuracy"] is not None else None,
            address_text=row["address_text"] or None,
            source=row["source"] or None,
            timestamp=row["timestamp"] or "",
        )

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-friendly location mapping."""
        return {
            "patient_id": self.patient_id,
            "latitude": self.latitude,
            "longitude": self.longitude,
            "accuracy": self.accuracy,
            "address_text": self.address_text,
            "source": self.source,
            "timestamp": self.timestamp,
        }


@dataclass(slots=True)
class SafeZone:
    """A simple circular safety zone for one patient."""

    patient_id: str
    label: str
    center_latitude: float
    center_longitude: float
    radius_meters: float
    enabled: bool = True
    updated_at: str = ""

    @classmethod
    def from_row(cls, row: Any) -> "SafeZone":
        """Build a safe-zone object from a SQLite row."""
        return cls(
            patient_id=row["patient_id"],
            label=row["label"] or "家庭安全区域",
            center_latitude=float(row["center_latitude"]),
            center_longitude=float(row["center_longitude"]),
            radius_meters=float(row["radius_meters"]),
            enabled=bool(row["enabled"]),
            updated_at=row["updated_at"] or "",
        )

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-friendly safe-zone mapping."""
        return {
            "patient_id": self.patient_id,
            "label": self.label,
            "center_latitude": self.center_latitude,
            "center_longitude": self.center_longitude,
            "radius_meters": self.radius_meters,
            "enabled": self.enabled,
            "updated_at": self.updated_at,
        }


@dataclass(slots=True)
class LocationAlert:
    """A caregiver-facing alert generated by location-safety evaluation."""

    patient_id: str
    alert_type: str
    severity: str
    message: str
    latitude: float
    longitude: float
    distance_meters: float
    created_at: str
    resolved: bool = False
    id: int | None = None

    @classmethod
    def from_row(cls, row: Any) -> "LocationAlert":
        """Build an alert object from a SQLite row."""
        return cls(
            id=row["id"],
            patient_id=row["patient_id"],
            alert_type=row["alert_type"],
            severity=row["severity"],
            message=row["message"],
            latitude=float(row["latitude"]),
            longitude=float(row["longitude"]),
            distance_meters=float(row["distance_meters"]),
            created_at=row["created_at"] or "",
            resolved=bool(row["resolved"]),
        )

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-friendly alert mapping."""
        return {
            "id": self.id,
            "patient_id": self.patient_id,
            "alert_type": self.alert_type,
            "severity": self.severity,
            "message": self.message,
            "latitude": self.latitude,
            "longitude": self.longitude,
            "distance_meters": self.distance_meters,
            "created_at": self.created_at,
            "resolved": self.resolved,
        }
